main_menu() {
    local i
    while i=$(rofi_menu "Settings" -1 "󰍹  Display" "󰏘  Appearance" "󰐥  Power and idle"); do
        case "$i" in
            0) choose_display ;;
            1) appearance_menu ;;
            2) power_menu ;;
