# Power and idle (hypridle, power-profiles-daemon)
# ----------------------------------------------------------------------------

# Timeouts in seconds, 0 = never. The defaults match hypr/hypridle.conf.
IDLE_KEYS=(dim lock screen_off suspend)
IDLE_LABELS=("Dim screen" "Lock screen" "Screen off" "Suspend")
IDLE_DEFAULTS=(150 300 330 3600)
IDLE_CHOICES_dim=(0 60 150 300 600)
IDLE_CHOICES_lock=(0 300 600 900 1800 3600)
IDLE_CHOICES_screen_off=(0 300 600 900 1800 3600)
IDLE_CHOICES_suspend=(0 900 1800 3600 7200)

# saved_idle <index into IDLE_KEYS>
saved_idle() {
    jq -r --arg k "${IDLE_KEYS[$1]}" --argjson d "${IDLE_DEFAULTS[$1]}" \
        '.idle[$k] // $d' "$GLOBAL_STATE"
}

duration_name() {
    awk -v s="$1" 'BEGIN {
        if (s == 0) print "Never"
        else if (s < 60) printf "%d s\n", s
        else if (s < 3600) printf "%g min\n", s / 60
        else printf "%g h\n", s / 3600
    }'
}

write_idle_conf() {
    local dim lock screen_off suspend
    dim=$(saved_idle 0)
    lock=$(saved_idle 1)
    screen_off=$(saved_idle 2)
    suspend=$(saved_idle 3)
    {
        echo "# Generated by ~/.config/hypr/scripts/settings.sh (Alt+Shift+S)."
        echo "# Do not edit by hand; use the settings menu or delete this file."
        cat << 'EOF2'
general {
    lock_cmd = pidof hyprlock || hyprlock
    before_sleep_cmd = loginctl lock-session
    after_sleep_cmd = hyprctl dispatch 'hl.dsp.dpms({ action = "enable" })'
}
EOF2
        [ "$dim" != "0" ] && printf '\nlistener {\n    timeout = %s\n    on-timeout = brightnessctl -s set 10\n    on-resume = brightnessctl -r\n}\n' "$dim"
        [ "$lock" != "0" ] && printf '\nlistener {\n    timeout = %s\n    on-timeout = loginctl lock-session\n}\n' "$lock"
        [ "$screen_off" != "0" ] && printf '\nlistener {\n    timeout = %s\n    on-timeout = hyprctl dispatch %s\n    on-resume = hyprctl dispatch %s\n}\n' \
            "$screen_off" "'hl.dsp.dpms({ action = \"disable\" })'" "'hl.dsp.dpms({ action = \"enable\" })'"
        [ "$suspend" != "0" ] && printf '\nlistener {\n    timeout = %s\n    on-timeout = systemctl suspend\n}\n' "$suspend"
    } > "$IDLE_CONF"
}

# hypridle does not reload its config, so restart it
restart_hypridle() {
    pkill -x hypridle
    setsid -f "$HOME/.config/hypr/scripts/hypridle.sh" > /dev/null 2>&1
}

# choose_idle <index into IDLE_KEYS>
choose_idle() {
    local idx="$1" key="${IDLE_KEYS[$1]}" current active=-1 rows=() i v
    local -n choices="IDLE_CHOICES_$key"
    current=$(saved_idle "$idx")
    for i in "${!choices[@]}"; do
        rows+=("$(duration_name "${choices[$i]}")")
        [ "${choices[$i]}" = "$current" ] && active=$i
    done
    i=$(rofi_menu "${IDLE_LABELS[$idx]}" "$active" "${rows[@]}") || return
    [ "$i" = "$active" ] && return
    v="${choices[$i]}"

    local tmp
    tmp=$(mktemp)
    jq --arg k "$key" --argjson v "$v" '.idle[$k] = $v' "$GLOBAL_STATE" > "$tmp" && mv "$tmp" "$GLOBAL_STATE"
    write_idle_conf
    restart_hypridle
}

# Power profiles are kept by power-profiles-daemon itself, so nothing is saved
choose_power_profile() {
    if ! command -v powerprofilesctl > /dev/null; then
        show_message "Power profile" "power-profiles-daemon is not installed"
        return
    fi
    local profiles=() current active=-1 i
    mapfile -t profiles < <(powerprofilesctl list | sed -n 's/^[* ] \(.*\):$/\1/p')
    current=$(powerprofilesctl get)
    for i in "${!profiles[@]}"; do
        [ "${profiles[$i]}" = "$current" ] && active=$i
    done
    i=$(rofi_menu "Power profile" "$active" "${profiles[@]}") || return
    [ "$i" = "$active" ] && return
    powerprofilesctl set "${profiles[$i]}"
}

reset_power() {
    local i tmp
    i=$(rofi_menu "Reset power and idle to defaults?" -1 "Reset" "Cancel") || return
    [ "$i" = "0" ] || return
    tmp=$(mktemp)
    jq 'del(.idle)' "$GLOBAL_STATE" > "$tmp" && mv "$tmp" "$GLOBAL_STATE"
    rm -f "$IDLE_CONF"
    restart_hypridle
}

power_menu() {
    local i idx rows
    while true; do
        rows=()
        for idx in "${!IDLE_KEYS[@]}"; do
            rows+=("$(row "${IDLE_LABELS[$idx]}" "$(duration_name "$(saved_idle "$idx")")")")
        done
        rows+=("$(row "Power profile" "$(powerprofilesctl get 2> /dev/null || echo "-")")")
        rows+=("Reset to defaults")
        i=$(rofi_menu "Power and idle" -1 "${rows[@]}") || return
        case "$i" in
            0 | 1 | 2 | 3) choose_idle "$i" ;;
            4) choose_power_profile ;;
            5) reset_power ;;
        esac
    done
}

